import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const UNICODE_VERSION = "18.0.0";
const SOURCE_URL = `https://www.unicode.org/Public/${UNICODE_VERSION}/ucd/CaseFolding.txt`;
const SOURCE_SHA256 = "a004797658a457bec4dc11683e39f69249ea3b595b752dbea6721c4c9f587b0d";
const COPYRIGHT_YEAR = 2026;

const output = resolve(import.meta.dirname, "../../src/core/case-folding-table.ts");

interface Mapping {
  readonly from: number;
  readonly to: readonly number[];
}

type Run = readonly [first: number, last: number, step: number, delta: number];

function hexList(field: string): number[] {
  return field.split(" ").map((hex) => Number.parseInt(hex, 16));
}

interface Mappings {
  readonly common: readonly Mapping[];
  readonly full: readonly Mapping[];
}

function mappingsOf(text: string): Mappings {
  const common: Mapping[] = [];
  const full: Mapping[] = [];

  for (const line of text.split("\n")) {
    const [from = "", status = "", to = ""] = line.split("#")[0]?.split(";") ?? [];
    const mapping = { from: Number.parseInt(from.trim(), 16), to: hexList(to.trim()) };

    if (status.trim() === "C") common.push(mapping);

    if (status.trim() === "F") full.push(mapping);
  }

  return { common, full };
}

function singleDelta({ from, to }: Readonly<Mapping>): number {
  const [target] = to;

  if (to.length !== 1 || target === undefined) {
    throw new Error(`U+${from.toString(16)} has a common folding of ${to.length} code points`);
  }

  return target - from;
}

interface Growing {
  readonly first: number;
  last: number;
  step: number;
  readonly delta: number;
}

function continues(run: Readonly<Growing>, from: number, delta: number): boolean {
  const gap = from - run.last;

  return run.delta === delta && gap > 0 && gap <= 2 && (run.first === run.last || gap === run.step);
}

function runsOf(common: readonly Mapping[]): Run[] {
  const runs: Growing[] = [];

  for (const mapping of common) {
    const delta = singleDelta(mapping);
    const run = runs.at(-1);

    if (run !== undefined && continues(run, mapping.from, delta)) {
      run.step = mapping.from - run.last;
      run.last = mapping.from;
    } else {
      runs.push({ first: mapping.from, last: mapping.from, step: 1, delta });
    }
  }

  return runs.map(({ first, last, step, delta }) => [first, last, step, delta]);
}

function rows(lines: readonly string[]): string {
  return lines.map((line) => `  [${line}],\n`).join("");
}

function moduleText(runs: readonly Run[], full: readonly Mapping[]): string {
  const runRows = rows(runs.map((run) => run.join(", ")));
  const expansionRows = rows(full.map(({ from, to }) => `${from}, [${to.join(", ")}]`));

  return `/*
 * SPDX-License-Identifier: Unicode-3.0
 * Copyright © ${COPYRIGHT_YEAR} Unicode®, Inc.
 */
/* oxlint-disable max-lines -- generated by tools/case-folding/build.ts, one table row per line */
export const CASE_FOLDING_RUNS: readonly (readonly [number, number, number, number])[] = [
${runRows}];

export const CASE_FOLDING_EXPANSIONS: readonly (readonly [number, readonly number[]])[] = [
${expansionRows}];
`;
}

const response = await fetch(SOURCE_URL);

if (!response.ok) {
  throw new Error(`${SOURCE_URL} answered ${response.status}`);
}

const text = await response.text();
const digest = createHash("sha256").update(text).digest("hex");

if (digest !== SOURCE_SHA256) {
  throw new Error(`${SOURCE_URL} has SHA-256 ${digest}, not the pinned ${SOURCE_SHA256}`);
}

const { common, full } = mappingsOf(text);

writeFileSync(output, moduleText(runsOf(common), full));
